CREATE TABLE IF NOT EXISTS rb_sessions(token_hash TEXT PRIMARY KEY,client TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS rb_rates(client TEXT NOT NULL,hour TEXT NOT NULL,uses INTEGER NOT NULL,PRIMARY KEY(client,hour));
CREATE TABLE IF NOT EXISTS rb_spend(period TEXT PRIMARY KEY,micros INTEGER NOT NULL CHECK(micros BETWEEN 0 AND 10000000));
CREATE TABLE IF NOT EXISTS rb_voice(id TEXT PRIMARY KEY,text_sha TEXT NOT NULL,state TEXT NOT NULL,expires INTEGER NOT NULL);
